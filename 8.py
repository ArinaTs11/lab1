# Задание 8. Найти произведение длин AC и BC.
# Точка C должна находиться между точками A и B.

a = float(input("Введите координату точки A: "))
b = float(input("Введите координату точки B: "))
c = float(input("Введите координату точки C: "))

if min(a, b) <= c <= max(a, b):
    ac = abs(c - a)
    bc = abs(b - c)

    print("Произведение длин AC и BC:", ac * bc)
else:
    print("Ошибка: точка C должна находиться между A и B.")