# Задание 4. Выполнить операции с квадратами двух чисел.

a = float(input("Введите первое ненулевое число: "))
b = float(input("Введите второе ненулевое число: "))

if a == 0 or b == 0:
    print("Ошибка: числа должны быть ненулевыми.")
else:
    a2 = a ** 2
    b2 = b ** 2

    print("Сумма квадратов:", a2 + b2)
    print("Разность квадратов:", a2 - b2)
    print("Произведение квадратов:", a2 * b2)
    print("Частное квадратов:", a2 / b2)