# Задание 5. Выполнить операции с модулями двух чисел.

a = float(input("Введите первое ненулевое число: "))
b = float(input("Введите второе ненулевое число: "))

if a == 0 or b == 0:
    print("Ошибка: числа должны быть ненулевыми.")
else:
    a = abs(a)
    b = abs(b)

    print("Сумма модулей:", a + b)
    print("Разность модулей:", a - b)
    print("Произведение модулей:", a * b)
    print("Частное модулей:", a / b)